// The token radar's empirical model: one snapshot in, one ranked board out.
//
// Unlike a flat multiple, the base multiple here is measured from the snapshot itself: for every
// live-token protocol the market already prices a market-cap-to-TVL ratio, and the median ratio of a
// category is what a pre-token protocol of that category is scored with. Categories with too few
// live samples fall back to the median over all live protocols, so no single outlier decides a
// category. Everything else follows only from the snapshot's own figures:
//
//   base         = tvl_usd x category_multiple
//   growth       = clamp(change_7d, -60, 120) per cent
//   growthMult   = 1 + (growth / 100) x 0.5
//   maturity     = 0.6 + min(age_days, 1095) / 1095 x 0.4   (age_days unknown: 365)
//   chainMult    = 1 + 0.03 x min(max(chains - 1, 0), 3)
//   implied      = max(1, round(base x growthMult x maturity x chainMult))
//
// The board covers every slug in the snapshot's watchlist (the floor, never a ceiling) and adds the
// pre-token, rankable protocols below the watchlist floor, by TVL, up to EARLY_ROWS. A protocol is
// pre-token when its index entry records no token at all (no market cap, no CoinGecko id, no
// symbol); live-token protocols are kept apart and shown with the market's own values, never mixed
// into the ranked board. No protocol name is ever special-cased: the same functions score every
// row, and every tie is broken by slug, so the board is deterministic.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The empirical model, measured from the snapshot: medians, sample counts and weights. */
export interface EmpiricalModel {
  version: 'radar-2';
  overall_median: number;
  category_multiples: Record<string, number>;
  category_samples: Record<string, number>;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  chain_bonus: number;
  chain_cap: number;
}

/** The model's version label: the dashboard names it and the rules quote it. */
export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the early radar carries, by TVL. */
export const EARLY_ROWS = 200;

/** How many live-token protocols the Live token view carries, by market cap. */
export const LIVE_ROWS = 24;

/** A category needs at least this many live-token samples before its own median is trusted. */
export const MIN_CATEGORY_SAMPLES = 3;

/** A category multiple is clamped into this range, so no thin market decides a value alone. */
export const MULTIPLE_FLOOR = 0.05;
export const MULTIPLE_CAP = 1.5;

/** Categories the board never ranks: exchanges, bridges and staked or restaked products. */
export const EXCLUDED_CATEGORIES = new Set(['CEX', 'Bridge', 'Canonical Bridge', 'Liquid Staking', 'Liquid Restaking', 'Restaked BTC']);

